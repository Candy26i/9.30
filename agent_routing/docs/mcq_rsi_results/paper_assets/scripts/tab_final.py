"""The final paper tables (2026-10-11), replacing the seven draft tables the user reviewed:
  tab_final_main     (main text)  one S_1 row, then SFT + GRPO (round 3) and SFT only (rounds 3 and 5); accuracy and calls
  tab_final_labels   (main text)  label quality from a common S_1 (A) and post-GRPO vs post-SFT collectors (B)
  tab_final_reliab   (appendix)   MARGENT seed spread on MedQA (A) and the key paired contrasts of the RSI runs (B)
No titles and no footnotes inside the tables; each has one caption sentence. Every RSI number comes from data.json.
Rounding is half-up on the exact value (e.g. 57/200 calls = 0.285 -> 0.29)."""
import json, statistics, sys
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
d = json.load(open(ROOT / "data.json"))
B = ["medqa", "mmlu_pro", "gpqa", "aqua"]
NAME = {"medqa": "MedQA", "mmlu_pro": "MMLU-Pro", "gpqa": "GPQA", "aqua": "AQuA-RAT"}
N_TEST, N_DEV = d["meta"]["n_test"], d["meta"]["n_dev"]
L, P = d["locked"], d["pairs"]

def r(x, nd):
    x = x if isinstance(x, Decimal) else Decimal(repr(x))
    return str(x.quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))
def exact(x, n, scale=100):
    """Value recomputed from its integer count: x is a stored rounded rate (in % if scale=100) over n questions."""
    k = round(x * n / scale)
    return Decimal(k) * scale / Decimal(n)
def acc(x): return r(x, 1)
def calls(x): return r(x, 2)
def sgn(x):
    s = r(x, 1)
    return ("+" + s if not s.startswith("-") else "$-$" + s[1:]) if s not in ("0.0", "-0.0") else "0.0"
def pv(p): return "$<$0.001" if p < 0.001 else r(p, 3 if p < 0.01 else 2)
BLUE = "rsiblue"
def dyn(s): return f"\\textcolor{{{BLUE}}}{{{s}}}"

PRE = ["% Generated by scripts/tab_final.py from data.json -- do not edit by hand.",
       "% Needs \\usepackage{booktabs,xcolor} and \\definecolor{rsiblue}{HTML}{2C5A7E} in the preamble."]

# ---------------------------------------------------------------- main table
ROWS = [("Base, letter only", "--", "base_only", None), ("Base system", "--", "base_system", None), ("rule", None, None, None),
        ("S$_1$", "1", "v3g/S_1", None),
        ("sec", "SFT + GRPO", None, None),
        ("Static", "3", "v3g/static", None), ("Dynamic", "3", "v3g/dynamic", "dyn"), ("Success", "3", "v3g/success", None),
        ("sec", "SFT only", None, None),
        ("Static", "3", "v3/static_sft", None), ("Dynamic", "3", "v3/dynamic_sft", "dyn"),
        ("Static", "5", "v3r5/static_sft", None), ("Dynamic", "5", "v3r5/dynamic_sft", "dyn")]
def cell(b, key):
    if key == "base_only":  # untrained base model, answers with the letter only (no tools, no reasoning)
        r_ = d["single_agent"][f"{b}:test"]["base_nocot_f"]
        return {"acc": r_["acc"], "calls": 0.0, "n": r_["n"]}
    if key == "base_system":  # untrained base model in the manager seat, with the same tools and advisors
        return d["base_system"][f"{b}:test"]
    m = L[f"{b}:test"].get(key)
    return None if m is None else m
best = {b: max(cell(b, k)["acc"] for _, _, k, _ in ROWS if k and cell(b, k)) for b in B}
T = PRE + [r"\begin{table*}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{6pt}",
     r"\begin{tabular}{lc" + "rr" * len(B) + "}", r"\toprule",
     r" & & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{NAME[b]}}}" for b in B) + r" \\",
     " ".join(f"\\cmidrule(lr){{{3 + 2 * i}-{4 + 2 * i}}}" for i in range(len(B))),
     r"Policy & Round & " + " & ".join(["Acc. & Calls"] * len(B)) + r" \\", r"\midrule"]
MD = ["| Policy | Round | " + " | ".join(f"{NAME[b]} Acc. | {NAME[b]} Calls" for b in B) + " |", "|:--|:-:|" + "--:|" * (2 * len(B))]
for name, rnd, key, style in ROWS:
    if name == "rule":
        T.append(r"\midrule"); continue
    if name == "sec":
        T += [r"\midrule", f"\\multicolumn{{{2 + 2 * len(B)}}}{{l}}{{\\textit{{{rnd}}}}} \\\\"]
        MD.append(f"| *{rnd}* |" + " |" * (1 + 2 * len(B)))
        continue
    tc, mc = [], []
    for b in B:
        m = cell(b, key)
        if m is None:
            tc += ["--", "--"]; mc += ["—", "—"]; continue
        a, c = acc(exact(m["acc"], m["n"])), calls(exact(m["calls"], m["n"], 1))
        ta, ma = (f"\\textbf{{{a}}}", f"**{a}**") if m["acc"] == best[b] else (a, a)
        tc += [ta, c]; mc += [ma, c]
    nm = dyn(name) if style else name
    row = f"{nm} & {rnd} & " + " & ".join(dyn(x) if style and x != "--" else x for x in tc) + r" \\"
    T.append(row); MD.append(f"| {name.replace('S$_1$', 'S₁')} | {rnd.replace('--', '—')} | " + " | ".join(mc) + " |")
_g = d["grpo"]["medqa"]
cap_main = (f"Locked-test accuracy (\\%) and advisor calls per question, single runs (MedQA {N_TEST['medqa']}, MMLU-Pro {N_TEST['mmlu_pro']} test, "
            f"GPQA {N_TEST['gpqa']}, AQuA-RAT {N_TEST['aqua']}; -- = not run); bold = best per benchmark. "
            f"A GRPO update is kept only if it passes the development gate; MedQA kept {_g['accepted_total']} of {_g['total']}. "
            "Base, letter only: the untrained model answers with the option letter, no tools. Base system: the untrained model as manager with the same advisors; unparseable answers count as wrong.")
T += [r"\bottomrule", r"\end{tabular}", f"\\caption{{{cap_main}}}", r"\label{tab:main}", r"\end{table*}"]

# ---------------------------------------------------------------- label quality
lq = {b: {row["labels"]: row for row in d["label_quality"][b]} for b in B}
LROWS = [("S_1", "S$_1$ (no extra training)"), ("r1", "R1 labels (static)"), ("r2", "R2 labels, from S$_1$"), ("r3", "R3 labels, from S$_2$"),
         ("r4", "R4 labels, from S$_3$"), ("r5", "R5 labels, from S$_4$")]
T2 = PRE + [r"\begin{table*}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{l" + "c" * len(B) + "}", r"\toprule",
      r"\multicolumn{" + str(1 + len(B)) + r"}{l}{\textit{A. One SFT from the same S$_1$: accuracy / calls}} \\", r"\midrule",
      r"Training labels & " + " & ".join(NAME[b] for b in B) + r" \\", r"\midrule"]
MD2 = ["**A. One SFT from the same S₁: accuracy / calls**", "", "| Training labels | " + " | ".join(NAME[b] for b in B) + " |", "|:--|" + "--:|" * len(B)]
for key, name in LROWS:
    vals = []
    for b in B:
        row = lq[b].get(key)
        vals.append("--" if row is None else f"{acc(exact(row['acc'], N_DEV[b]))} / {calls(exact(row['calls'], N_DEV[b], 1))}")
    T2.append(f"{name} & " + " & ".join(vals) + r" \\")
    MD2.append(f"| {name.replace('S$_1$', 'S₁').replace('S$_2$', 'S₂').replace('S$_3$', 'S₃').replace('S$_4$', 'S₄')} | " + " | ".join(v.replace('--', '—') for v in vals) + " |")
    if key == "S_1":
        T2.append(r"\midrule")
gq = d["grpo_data_quality"]
# panel B: one row per label round, one "before / after GRPO" cell per benchmark (same questions, same run)
DQ = {}  # (round of the labels, bench) -> (S_k acc, G_k acc); labels collected by the round-k model are round k+1 labels
for b in ("mmlu_pro", "gpqa", "aqua"):
    rows = {row["labels"]: row for row in gq[b]}
    for k in sorted({int(x[1:]) for x in rows}):
        DQ[(k + 1, b)] = (exact(rows[f"S{k}"]["acc"], N_DEV[b]), exact(rows[f"G{k}"]["acc"], N_DEV[b]))
DROWS = sorted({rk for rk, _ in DQ})
T2 += [r"\midrule", r"\multicolumn{" + str(1 + len(B)) + r"}{l}{\textit{B. Labels re-collected on the same questions before / after GRPO: accuracy}} \\", r"\midrule"]
MD2 += ["", "**B. Labels re-collected on the same questions before / after GRPO: accuracy**", "", "| Collector | " + " | ".join(NAME[b] for b in B) + " |", "|:--|" + "--:|" * len(B)]
for rk in DROWS:
    vals = [f"{acc(DQ[(rk, b)][0])} / {acc(DQ[(rk, b)][1])}" if (rk, b) in DQ else "--" for b in B]
    T2.append(f"Round-{rk - 1} model, S$_{rk - 1}$ / G$_{rk - 1}$ & " + " & ".join(vals) + r" \\")
    sub = "₀₁₂₃₄₅₆₇₈₉"[rk - 1]
    MD2.append(f"| Round-{rk - 1} model, S{sub} / G{sub} | " + " | ".join(v.replace("--", "—") for v in vals) + " |")
cap_lab = (f"Development accuracy (\\%) and calls per question of a manager trained once from S$_1$ on one label set (MedQA {N_DEV['medqa']}, "
           f"MMLU-Pro {N_DEV['mmlu_pro']}, GPQA {N_DEV['gpqa']}, AQuA-RAT {N_DEV['aqua']} questions; -- = not collected). "
           "B uses the SFT + GRPO run, so its S$_k$ labels are a separate collection from A's.")
T2 += [r"\bottomrule", r"\end{tabular}", f"\\caption{{{cap_lab}}}", r"\label{tab:labels}", r"\end{table*}"]

# ---------------------------------------------------------------- reliability (appendix)
SEEDS = [(80.5, 52.5), (81.5, 55.5), (79.5, 47.0)]  # MARGENT paper, MedQA final manager, three training seeds (dev), as in the user's table
ma, sa_ = statistics.mean(x for x, _ in SEEDS), statistics.stdev(x for x, _ in SEEDS)
mc_, sc = statistics.mean(y for _, y in SEEDS), statistics.stdev(y for _, y in SEEDS)
CON = [("Dynamic $-$ Static (R3, SFT only)", "v3/dynamic_sft - v3/static_sft"),
       ("Dynamic: with $-$ without GRPO (R3)", "v3g/dynamic - v3/dynamic_sft"),
       ("Dynamic: R5 $-$ R3 (SFT only)", "v3r5/dynamic_sft - v3/dynamic_sft"),
       ("S$_1$ evaluated twice (GRPO run $-$ SFT run)", "v3g/S_1 - v3/S_1")]
T3 = PRE + [r"\begin{table*}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{3.5pt}",
      r"\begin{tabular}{l" + "c" * len(B) + "}", r"\toprule",
      r"\multicolumn{" + str(1 + len(B)) + r"}{l}{\textit{A. Original MARGENT, MedQA development, three training seeds}} \\", r"\midrule",
      r" & Seed 1 & Seed 2 & Seed 3 & Mean $\pm$ SD \\", r"\midrule"]
MD3 = ["**A. Original MARGENT, MedQA development, three training seeds**", "", "| | Seed 1 | Seed 2 | Seed 3 | Mean ± SD |", "|:--|--:|--:|--:|--:|"]
for lab, idx, m_, sd in (("Accuracy (\\%)", 0, ma, sa_), ("Questions with a call (\\%)", 1, mc_, sc)):
    vals = [acc(x[idx]) for x in SEEDS]
    T3.append(f"{lab} & " + " & ".join(vals) + f" & {acc(m_)} $\\pm$ {acc(sd)} \\\\")
    MD3.append(f"| {lab.replace(chr(92), '')} | " + " | ".join(vals) + f" | {acc(m_)} ± {acc(sd)} |")
T3 += [r"\midrule", r"\multicolumn{" + str(1 + len(B)) + r"}{l}{\textit{B. Paired contrasts on the locked tests: $\Delta$ accuracy in points (p)}} \\", r"\midrule",
       r"Contrast & " + " & ".join(NAME[b] for b in B) + r" \\", r"\midrule"]
MD3 += ["", "**B. Paired contrasts on the locked tests: Δ accuracy in points (p)**", "", "| Contrast | " + " | ".join(NAME[b] for b in B) + " |", "|:--|" + "--:|" * len(B)]
for name, key in CON:
    vals = []
    for b in B:
        c = P[f"{b}:test"].get(key)
        if c is None:
            vals.append("--"); continue
        kb, ka = [k.strip() for k in key.split(" - ")]
        mb, ma_ = L[f"{b}:test"][kb], L[f"{b}:test"][ka]
        delta = exact(mb["acc"], mb["n"]) - exact(ma_["acc"], ma_["n"])
        assert abs(float(delta) - c["d_acc"]) < 0.06, (b, key, delta, c["d_acc"])
        vals.append(f"{sgn(delta)} ({pv(c['p'])})")
    T3.append(name + " & " + " & ".join(vals) + r" \\")
    MD3.append("| " + name.replace("$-$", "−").replace("S$_1$", "S₁") + " | " + " | ".join(v.replace("$-$", "−").replace("$<$", "<").replace("--", "—") for v in vals) + " |")
cap_rel = ("A: depth 2, 400 questions, $\\rho = 3$; sample SD over seeds. B: single RSI runs; two-sided paired bootstrap (10{,}000 resamples, unadjusted); -- = no round 5.")
T3 += [r"\bottomrule", r"\end{tabular}", f"\\caption{{{cap_rel}}}", r"\label{tab:reliability}", r"\end{table*}"]

out = ROOT / "tab"
for name, tex, md, cap in (("tab_final_main", T, MD, cap_main), ("tab_final_labels", T2, MD2, cap_lab), ("tab_final_reliab", T3, MD3, cap_rel)):
    (out / f"{name}.tex").write_text("\n".join(tex) + "\n")
    capm = cap.replace("\\%", "%").replace("--", "–").replace("S$_1$", "S₁").replace("S$_k$", "S_k").replace("$\\rho = 3$", "ρ = 3").replace("{,}", ",")
    (out / f"{name}.md").write_text("\n".join(md) + "\n\n" + capm + "\n")
    print("wrote", name)
