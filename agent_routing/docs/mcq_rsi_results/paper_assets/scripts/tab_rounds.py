"""tab_rounds: locked-test results of the no-GRPO chain (v3) at round 3 and round 5 per arm, with paired-bootstrap deltas
(r5 - r3 within arm, r5 - S_1, dynamic - static at r5). Writes tab/tab_rounds.tex (booktabs) and tab/tab_rounds.md."""
import sys, json
from pathlib import Path
sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[1]) + "")
import style

d = json.load(open(style.ROOT / "data.json"))
LOCKED, PAIRS = d["locked"], d["pairs"]
TAB_DIR = style.ROOT / "tab"; TAB_DIR.mkdir(parents=True, exist_ok=True)

POOLS = [("medqa:test", "MedQA"), ("mmlu_pro:test", "MMLU-Pro"), ("gpqa:test", "GPQA"), ("aqua:test", "AQuA-RAT")]
EXTRA = [("mmlu_pro:test_paper", "MMLU-Pro (test_paper)")]
ARMS = ["dynamic", "static"]
MINUS = {"tex": "$-$", "md": "\u2212"}
DASH = {"tex": "--", "md": "\u2013"}


def f_acc(v): return f"{v:.1f}"
def f_calls(v): return f"{v:.2f}"
def f_delta(v, mode):
    s = f"{v:+.1f}"
    return s.replace("-", MINUS[mode]) if s.startswith("-") else s
def f_p(v, mode):
    if v < 0.001:
        return "$<$0.001" if mode == "tex" else "<0.001"
    return f"{v:.3f}"
def bold(s, mode): return f"\\textbf{{{s}}}" if mode == "tex" else f"**{s}**"
def esc(s, mode): return s.replace("_", "\\_") if mode == "tex" else s


def block(key, name, mode):
    """Two rows (dynamic, static) for one locked pool."""
    L, P = LOCKED[key], PAIRS[key]
    s1 = L["v3/S_1"]
    r3 = {a: L.get(f"v3/{a}_sft") for a in ARMS}
    r5 = {a: L.get(f"v3r5/{a}_sft") for a in ARMS}
    accs = [s1["acc"]] + [r[a]["acc"] for r in (r3, r5) for a in ARMS if r[a] is not None]
    best = max(accs)
    def acc_cell(v):
        return bold(f_acc(v), mode) if abs(v - best) < 1e-9 else f_acc(v)
    dash = DASH[mode]
    rows, summary = [], {"S_1": s1["acc"]}
    for i, a in enumerate(ARMS):
        c = [esc(name, mode) if i == 0 else "", a]
        c += [acc_cell(s1["acc"]), f_calls(s1["calls"])] if i == 0 else ["", ""]
        c += [acc_cell(r3[a]["acc"]), f_calls(r3[a]["calls"])]
        summary[f"{a}_r3"] = (r3[a]["acc"], r3[a]["calls"])
        if r5[a] is None:
            c += [dash, dash, dash, dash, dash, dash]
        else:
            c += [acc_cell(r5[a]["acc"]), f_calls(r5[a]["calls"])]
            pr = P[f"v3r5/{a}_sft - v3/{a}_sft"]; ps = P[f"v3r5/{a}_sft - v3/S_1"]
            c += [f_delta(pr["d_acc"], mode), f_p(pr["p"], mode), f_delta(ps["d_acc"], mode), f_p(ps["p"], mode)]
            summary[f"{a}_r5"] = (r5[a]["acc"], r5[a]["calls"])
            summary[f"{a}_r5-r3"] = (pr["d_acc"], pr["p"]); summary[f"{a}_r5-S1"] = (ps["d_acc"], ps["p"])
        if i == 0:
            pd = P.get("v3r5/dynamic_sft - v3r5/static_sft")
            if pd is None:
                c += [dash, dash]
            else:
                c += [f_delta(pd["d_acc"], mode), f_p(pd["p"], mode)]; summary["dyn-static_r5"] = (pd["d_acc"], pd["p"])
        else:
            c += ["", ""]
        rows.append(c)
    return rows, summary


CAPTION = ("Locked-test accuracy (\\%) and calls per question for the no-GRPO chain (v3) at rounds 3 and 5, by arm. "
           "S$_1$ is round 1. $\\Delta$(r5$-$r3) compares round 5 with round 3 of the same arm; $\\Delta$ vs S$_1$ compares "
           "round 5 with S$_1$; dyn$-$static compares the two arms at round 5. $p$: two-sided paired bootstrap (10k resamples). "
           "Locked tests: MedQA 500, MMLU-Pro 500 (test), GPQA 100, AQuA 254. GPQA ran three rounds only, so its round-5 cells "
           "are empty. MMLU-Pro test\\_paper overlaps the training pools and is shown for completeness. "
           "Bold marks the best accuracy per pool.")

# ---------------- LaTeX ----------------
tex = []
tex.append("% generated by scripts/tab_rounds.py from data.json -- do not edit by hand")
tex.append("\\begin{table*}[t]\n\\centering\n\\footnotesize\n\\setlength{\\tabcolsep}{3.5pt}")
tex.append(f"\\caption{{{CAPTION}}}\n\\label{{tab:rounds}}")
tex.append("\\begin{tabular}{llrrrrrrrrrrrr}\n\\toprule")
tex.append(" & & \\multicolumn{2}{c}{S$_1$ (r1)} & \\multicolumn{2}{c}{Round 3} & \\multicolumn{2}{c}{Round 5} & "
           "\\multicolumn{2}{c}{$\\Delta$(r5$-$r3)} & \\multicolumn{2}{c}{$\\Delta$ vs S$_1$ (r5)} & \\multicolumn{2}{c}{dyn$-$static (r5)} \\\\")
tex.append("\\cmidrule(lr){3-4} \\cmidrule(lr){5-6} \\cmidrule(lr){7-8} \\cmidrule(lr){9-10} \\cmidrule(lr){11-12} \\cmidrule(lr){13-14}")
tex.append("Benchmark & Arm & Acc & Calls & Acc & Calls & Acc & Calls & $\\Delta$acc & $p$ & $\\Delta$acc & $p$ & $\\Delta$acc & $p$ \\\\\n\\midrule")
summaries = {}
for key, name in POOLS:
    rows, summaries[key] = block(key, name, "tex")
    tex += [" & ".join(r) + " \\\\" for r in rows]
tex.append("\\midrule")
for key, name in EXTRA:
    rows, summaries[key] = block(key, name, "tex")
    tex += [" & ".join(r) + " \\\\" for r in rows]
tex.append("\\bottomrule\n\\end{tabular}\n\\end{table*}")
(TAB_DIR / "tab_rounds.tex").write_text("\n".join(tex) + "\n")

# ---------------- Markdown twin ----------------
md = []
md.append("**Table: no-GRPO chain (v3), locked test at rounds 3 and 5.** " + CAPTION.replace("\\%", "%").replace("S$_1$", "S\u2081")
          .replace("$\\Delta$", "\u0394").replace("$-$", "\u2212").replace("$p$", "p").replace("test\\_paper", "test_paper"))
md.append("")
hdr = ["Benchmark", "Arm", "S\u2081 acc", "S\u2081 calls", "r3 acc", "r3 calls", "r5 acc", "r5 calls",
       "\u0394acc (r5\u2212r3)", "p", "\u0394acc vs S\u2081 (r5)", "p", "\u0394acc dyn\u2212static (r5)", "p"]
md.append("| " + " | ".join(hdr) + " |")
md.append("|" + "|".join([":--", ":--"] + ["--:"] * (len(hdr) - 2)) + "|")
for key, name in POOLS + EXTRA:
    rows, _ = block(key, name, "md")
    md += ["| " + " | ".join(r) + " |" for r in rows]
(TAB_DIR / "tab_rounds.md").write_text("\n".join(md) + "\n")

print((TAB_DIR / "tab_rounds.tex"), (TAB_DIR / "tab_rounds.md"))
print(json.dumps(summaries, indent=1))
