"""tab_grpo_log: FA-GRPO acceptance log (appendix), one row per decision in data.grpo[bench].decisions, plus a
summary line per benchmark. Writes tab/tab_grpo_log.tex (booktabs) and tab/tab_grpo_log.md. All numbers come from
data.json; rounding is half-up (Decimal) so that e.g. a stored 0.005 prints as +0.01 and -0.015 as -0.02."""
import json
import re
import sys
from decimal import Decimal, ROUND_HALF_UP

sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parents[1]) + "")
import style  # noqa: E402  (BENCH_ORDER / BENCH_LABEL; no plotting here)

ROOT = style.ROOT
TAB_DIR = ROOT / "tab"
D = json.load(open(ROOT / "data.json"))
G, SETUP = D["grpo"], D["setup"]


# ----------------------------------------------------------------------------------------------------------- helpers
def rnd(v, nd):
    return Decimal(str(v)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP)


def signed(v, nd, which):
    """Signed delta: '+0.5' / '-1.5'; zero prints as '+0.0'. LaTeX gets math mode for a true minus sign."""
    d = rnd(v, nd)
    s = f"{abs(d):.{nd}f}"
    sign = "-" if d < 0 else "+"
    if which == "tex":
        return f"${sign}{s}$"
    return ("−" if sign == "-" else "+") + s


def reason_short(dec, which):
    if dec["accepted"]:
        return "accepted"
    out = []
    for r in dec["reasons"]:
        if r.startswith("accuracy"):
            out.append(r"acc $<$ S$_k - 1$\,pt" if which == "tex" else "acc < S_k − 1 pt")
        elif "uninformative" in r:
            out.append("uninformative")
        elif "failed its gate" in r:
            out.append("validity gate")
        else:
            raise ValueError(f"unmapped reason: {r}")
    return "; ".join(out)


def run_short(dec, bench, which):
    r = dec["run"]
    r = r[len(bench) + 1:] if r.startswith(bench + "_") else r
    return r.replace("_", r"\_") if which == "tex" else r


def arm_name(dec):
    return "shared" if dec["arm"].startswith("shared") else dec["arm"]


def row(dec, bench, which, first):
    return [style.BENCH_LABEL[bench] if first else "",
            run_short(dec, bench, which),
            str(dec["round"]),
            arm_name(dec),
            "yes" if dec["accepted"] else "no",
            signed(dec["d_acc_dev"], 1, which),
            signed(dec["d_calls_dev"], 2, which),
            f"{rnd(dec['informative_frac'] * 100, 1):.1f}",
            f"{dec['selected_step']}/{dec['steps']}",
            reason_short(dec, which)]


def summary(bench):
    g = G[bench]
    arms = ", ".join(f"{a} {g['per_arm'][a]['accepted']}/{g['per_arm'][a]['total']}" for a in ("dynamic", "static", "success"))
    return f"{style.BENCH_LABEL[bench]}: accepted {g['accepted_total']} / {g['total']} decisions ({arms})"


# consistency checks against the stored per-benchmark counts
for b in style.BENCH_ORDER:
    decs = G[b]["decisions"]
    assert len(decs) == G[b]["total"], b
    assert sum(d["accepted"] for d in decs) == G[b]["accepted_total"], b
    for d in decs:  # every decision's stage must match its round / arm
        assert d["stage"].startswith(f"r{d['round']}/"), d["stage"]
        assert d["steps"] == d["grpo_steps"], d["stage"]

# caption ingredients from data.setup
gr = SETUP["grpo"]
dev = ", ".join(f"{style.BENCH_LABEL[b]} {SETUP['pools']['dev'][b]}" for b in style.BENCH_ORDER)
inf_pct = f"{rnd(gr['informative_min_fraction'] * 100, 0):.0f}"
tol_pt = f"{rnd(SETUP['gates']['acc_tolerance'] * 100, 0):.0f}"
HEAD = ["Benchmark", "Run", "Round", "Arm", "Accepted", "Acc.\\ (pt)", "Calls", "Inf.\\ (\\%)", "Step", "Reason"]

# ------------------------------------------------------------------------------------------------------------ LaTeX
cap = (rf"FA-GRPO acceptance log for the v3+GRPO chains, one row per decision; round 1 is shared by the three arms. "
       rf"$\Delta$ columns are the candidate G$_k$ minus the round's SFT manager S$_k$ on the development pools ({dev}): "
       rf"accuracy in points and calls per question. Inf.: share of revision states with $J \in (0.02, 0.98)$; a stage is "
       rf"informative at $\geq$\,{inf_pct}\%. Step: selected checkpoint / steps run ({gr['steps']} planned); a run with fewer "
       rf"steps was stopped by the guard (every {gr['guard_every']} steps on a {gr['guard_probe_size']}-question probe) and rolled "
       rf"back to the last good checkpoint, 0 being the SFT checkpoint. A candidate is rejected when its dev accuracy falls below "
       rf"S$_k - {tol_pt}$\,pt, when the stage is uninformative, or when its dev evaluation fails the valid-answer-rate gate; "
       rf"a rejected round keeps G$_k$ $:=$ S$_k$. Per-arm counts include the shared round-1 decision.")
L = [r"% generated by scripts/tab_grpo_log.py from data.json -- do not edit by hand",
     r"% requires \usepackage{booktabs}",
     r"\begin{table*}[t]", r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{3pt}",
     rf"\caption{{{cap}}}", r"\label{tab:grpo_log}",
     r"\begin{tabular}{@{}llclcrrrcl@{}}", r"\toprule",
     r"Benchmark & Run & Round & Arm & Accepted & \multicolumn{2}{c}{$\Delta$ vs.\ S$_k$ (dev)} & \multicolumn{2}{c}{FA-GRPO} & Reason \\",
     r"\cmidrule(lr){6-7} \cmidrule(lr){8-9}",
     " & ".join(["", "", "", "", ""] + HEAD[5:9] + [""]) + r" \\",
     r"\midrule"]
for bi, b in enumerate(style.BENCH_ORDER):
    if bi:
        L.append(r"\addlinespace")
    for i, dec in enumerate(G[b]["decisions"]):
        L.append(" & ".join(row(dec, b, "tex", i == 0)) + r" \\")
    L.append(rf"\multicolumn{{10}}{{@{{}}l}}{{\textit{{{summary(b)}}}}} \\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
TAB_DIR.mkdir(parents=True, exist_ok=True)
(TAB_DIR / "tab_grpo_log.tex").write_text("\n".join(L) + "\n")

# --------------------------------------------------------------------------------------------------------- Markdown
cap_md = (f"FA-GRPO acceptance log for the v3+GRPO chains, one row per decision; round 1 is shared by the three arms. "
          f"Δ columns are the candidate G_k minus the round's SFT manager S_k on the development pools ({dev}): accuracy in "
          f"points and calls per question. Inf.: share of revision states with J ∈ (0.02, 0.98); a stage is informative at "
          f"≥ {inf_pct}%. Step: selected checkpoint / steps run ({gr['steps']} planned); a run with fewer steps was stopped by "
          f"the guard (every {gr['guard_every']} steps on a {gr['guard_probe_size']}-question probe) and rolled back to the last "
          f"good checkpoint, 0 being the SFT checkpoint. A candidate is rejected when its dev accuracy falls below S_k − {tol_pt} pt, "
          f"when the stage is uninformative, or when its dev evaluation fails the valid-answer-rate gate; a rejected round keeps "
          f"G_k := S_k. Per-arm counts include the shared round-1 decision.")
M = [f"**Table: {cap_md}**", "",
     "| Benchmark | Run | Round | Arm | Accepted | ΔAcc. (pt) | ΔCalls | Inf. (%) | Step | Reason |",
     "|:--|:--|:-:|:--|:-:|--:|--:|--:|:-:|:--|"]
for b in style.BENCH_ORDER:
    for i, dec in enumerate(G[b]["decisions"]):
        M.append("| " + " | ".join(row(dec, b, "md", i == 0)) + " |")
    M.append(f"| *{summary(b)}* |" + " |" * 9)
(TAB_DIR / "tab_grpo_log.md").write_text("\n".join(M) + "\n")

print(TAB_DIR / "tab_grpo_log.tex")
print(TAB_DIR / "tab_grpo_log.md")
# compact verification summary
for b in style.BENCH_ORDER:
    print(summary(b))
