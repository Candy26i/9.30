"""Appendix tables (2026-10-11), same conventions as tab_final.py: no titles or footnotes inside, one short caption, numbers
from data.json / appendix.json only, half-up rounding from exact counts where counts exist.
  tab_app_advisors   advisor A/B: base model with role prompt vs the paper LoRA vs a retrained LoRA (dev, fixed base solver)
  tab_app_draft      draft letters: supervising the draft (v1) vs route-only loss (v3), dynamic arm, MedQA and AQuA-RAT
  tab_app_single     single-model answering without advisors: base / S_1 / RSI letter-only, and S_1 / RSI drafts
  tab_app_tokens     where the tokens go (manager vs advisor, input vs output) and advisor-side tokens per call by role
  tab_app_mix        which advisors each policy calls (calls per 100 questions), locked tests
  tab_app_testpaper  MMLU-Pro test_paper (overlaps training pools)"""
import json
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
d = json.load(open(ROOT / "data.json")); A = json.load(open(ROOT / "appendix.json"))
B = ["medqa", "mmlu_pro", "gpqa", "aqua"]
NAME = {"medqa": "MedQA", "mmlu_pro": "MMLU-Pro", "gpqa": "GPQA", "aqua": "AQuA-RAT"}
N_TEST, N_DEV = d["meta"]["n_test"], d["meta"]["n_dev"]
PRE = ["% Generated by scripts/tab_appendix.py from data.json and appendix.json -- do not edit by hand.", "% Needs \\usepackage{booktabs}."]

def q(x, nd):
    x = x if isinstance(x, Decimal) else Decimal(repr(x))
    return str(x.quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))
def exact(x, n, scale=100):
    return Decimal(round(x * n / scale)) * scale / Decimal(n)
def acc(x, n=None): return "--" if x is None else q(exact(x, n) if n else x, 1)
def sgn(x):
    s = q(x, 1)
    return "0.0" if s in ("0.0", "-0.0") else ("+" + s if not s.startswith("-") else "$-$" + s[1:])
def pv(p): return "$<$0.001" if p < 0.001 else q(p, 3 if p < 0.01 else 2)
def md(s): return (s.replace("$-$", "−").replace("$<$", "<").replace("S$_1$", "S₁").replace("\\%", "%").replace("--", "—").replace("$\\Delta$", "Δ")
                   .replace("\\textit{", "").replace("\\textbf{", "**").replace("{,}", ",").replace("\\_", "_"))
def write(name, tex, mdrows, cap):
    (ROOT / "tab" / f"{name}.tex").write_text("\n".join(PRE + tex) + "\n")
    (ROOT / "tab" / f"{name}.md").write_text("\n".join(mdrows) + "\n\n" + md(cap) + "\n")
    print("wrote", name)
def begin(cols, size="\\small", sep="5pt", star=True):
    env = "table*" if star else "table"
    return [f"\\begin{{{env}}}[t]", "\\centering", size, f"\\setlength{{\\tabcolsep}}{{{sep}}}", f"\\begin{{tabular}}{{{cols}}}", "\\toprule"]
def end(cap, label, star=True):
    env = "table*" if star else "table"
    return ["\\bottomrule", "\\end{tabular}", f"\\caption{{{cap}}}", f"\\label{{{label}}}", f"\\end{{{env}}}"]

# ------------------------------------------------------------------ advisors
ab = A["advisor_ab"]; ROLES = ["extractor", "reasoner", "verifier"]
T = begin("llrrrrr") + [r" & & Base & \multicolumn{2}{c}{Paper LoRA} & \multicolumn{2}{c}{Retrained LoRA} \\", r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
                         r"Benchmark & Advisor & Acc. & Acc. & $\Delta$ (p) & Acc. & $\Delta$ (p) \\", r"\midrule"]
M = ["| Benchmark | Advisor | Base Acc. | Paper LoRA Acc. | Paper LoRA Δ (p) | Retrained LoRA Acc. | Retrained LoRA Δ (p) |", "|:--|:--|--:|--:|--:|--:|--:|"]
for b in B:
    for i, role in enumerate(ROLES):
        r = ab["per_bench"][b]["kinds"][role]
        nb = ab["per_bench"][b]["n"]
        cells = [acc(r["base"]["acc"], nb)]
        for arm in ("lora", "v2"):
            cells += [acc(r[arm]["acc"], nb), f"{sgn(r[arm]['minus_base_pp'])} ({pv(r[arm]['sign_p'])})"]
        lab = (NAME[b] + f" ({ab['per_bench'][b]['n']})") if i == 0 else ""
        T.append(f"{lab} & {role.capitalize()} & " + " & ".join(cells) + r" \\"); M.append(f"| {lab} | {role.capitalize()} | " + " | ".join(md(c) for c in cells) + " |")
    T.append(r"\midrule")
ntot = sum(ab["per_bench"][b]["n"] for b in B)
for i, role in enumerate(ROLES):
    base_acc = sum(ab["per_bench"][b]["kinds"][role]["base"]["acc"] * ab["per_bench"][b]["n"] for b in B) / ntot
    cells = [acc(base_acc)]
    for arm in ("lora", "v2"):
        pa = sum(ab["per_bench"][b]["kinds"][role][arm]["acc"] * ab["per_bench"][b]["n"] for b in B) / ntot; P = ab["pooled"][role][arm]
        cells += [acc(pa), f"{sgn(P['minus_base_pp'])} ({pv(P['sign_p'])})"]
    lab = f"Pooled ({ntot})" if i == 0 else ""
    T.append(f"{lab} & {role.capitalize()} & " + " & ".join(cells) + r" \\"); M.append(f"| {lab} | {role.capitalize()} | " + " | ".join(md(c) for c in cells) + " |")
lc = A["lora_check"]["verifier"]
cap = (f"Advisor A/B on the development pools: a fixed base-model solver re-answers after one advisor output; $\\Delta$ is versus the base model with the same role prompt "
       f"(exact sign test). Paper LoRA is the paper's adapter loaded correctly; as served in the paper (vLLM, unrenamed weight keys) the Verifier adapter reproduced the base model "
       f"on {lc['original_vs_base_identical']}/{lc['n_prompts']} prompts.")
write("tab_app_advisors", T + end(cap, "tab:app_advisors"), M, cap)

# ------------------------------------------------------------------ draft supervision
dr = A["draft"]
ROWSD = [("S$_1$", "S_1"), ("v1 dynamic, R3", "v1 dynamic R3"), ("v1 dynamic, R5", "v1 dynamic R5"), ("v3 dynamic, R3", "v3 dynamic R3"), ("v3 dynamic, R5", "v3 dynamic R5")]
T = begin("l" + "rrrr" * 2, sep="4pt") + [r" & " + " & ".join(f"\\multicolumn{{4}}{{c}}{{{NAME[b]}}}" for b in ("medqa", "aqua")) + r" \\",
                                          r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}", r"Policy" + r" & Drafts B (\\%) & Draft acc. & Acc. & Calls" * 2 + r" \\", r"\midrule"]
M = ["| Policy | " + " | ".join(f"{NAME[b]} {c}" for b in ("medqa", "aqua") for c in ("Drafts B (%)", "Draft acc.", "Acc.", "Calls")) + " |", "|:--|" + "--:|" * 8]
for name, key in ROWSD:
    cells = []
    for b in ("medqa", "aqua"):
        r = dr[b][key]
        cells += [q(r["draft_B_pct"], 1), "--" if r["draft_acc"] is None else q(r["draft_acc"], 1), q(r["acc"], 1), q(r["calls"], 2)]
    T.append(f"{name} & " + " & ".join(cells) + r" \\"); M.append(f"| {md(name)} | " + " | ".join(md(c) for c in cells) + " |")
    if key == "S_1": T.append(r"\midrule")
tb = {b: q(dr[b]["S_1"]["truth_B_pct"], 1) for b in ("medqa", "aqua")}
cap = (f"Locked-test drafts of the dynamic arm when SFT supervises the manager's own draft (v1) or only the routing decision (v3); the true share of B is "
       f"{tb['medqa']}\\% (MedQA) and {tb['aqua']}\\% (AQuA-RAT). v1 MedQA R5 was recorded before its per-question outputs were lost.")
write("tab_app_draft", T + end(cap, "tab:app_draft"), M, cap)

# ------------------------------------------------------------------ single-model answering
SA = d["single_agent"]
ROWSS = [("Base, letter only", "base_nocot_f"), ("S$_1$, letter only", "s1_nocot_f"), ("Dynamic R3 (SFT), letter only", "dyn3_nocot_f"),
         ("S$_1$, draft", "s1_manager_notools"), ("Dynamic R3 (SFT), draft", "dyn3_manager_notools")]
T = begin("l" + "r" * len(B), size="\\footnotesize", star=False, sep="3pt") + ["Model & " + " & ".join({"medqa": "MedQA", "mmlu_pro": "MMLU-Pro", "gpqa": "GPQA", "aqua": "AQuA"}[b] for b in B) + r" \\", r"\midrule"]
M = ["| Model | " + " | ".join(NAME[b] for b in B) + " |", "|:--|" + "--:|" * len(B)]
for name, v in ROWSS:
    cells = [acc(SA[f"{b}:test"][v]["acc"], SA[f"{b}:test"][v]["n"]) for b in B]
    T.append(f"{name} & " + " & ".join(cells) + r" \\"); M.append(f"| {md(name)} | " + " | ".join(cells) + " |")
    if v == "dyn3_nocot_f": T.append(r"\midrule")
cap = "Locked-test accuracy (\\%) with no advisor calls: answering with the option letter only, or the manager's draft with tools removed."
write("tab_app_single", T + end(cap, "tab:app_single", star=False), M, cap)

# ------------------------------------------------------------------ tokens
TK = A["tokens"]
T = begin("ll" + "rrrrrr", sep="4pt") + [r" & & \multicolumn{2}{c}{Manager} & \multicolumn{2}{c}{Advisors} & & \\", r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
                                       r"Benchmark & Policy & Input & Output & Input & Output & Total & Calls \\", r"\midrule"]
M = ["| Benchmark | Policy | Manager input | Manager output | Advisor input | Advisor output | Total | Calls |", "|:--|:--|--:|--:|--:|--:|--:|--:|"]
fmt = lambda v: "--" if v is None else f"{Decimal(repr(v)).quantize(Decimal(1), rounding=ROUND_HALF_UP):,}"
for b in B:
    for i, pol in enumerate(["Base system", "S_1", "RSI dynamic"]):  # RSI dynamic = Dynamic R3 (+GRPO)
        r = TK[b]["rows"].get(pol)
        if r is None: continue
        cells = [fmt(r[c]) for c in ("mgr_in", "mgr_out", "adv_in", "adv_out", "total")] + [q(exact(r["calls"], r["n"], 1) if r.get("n") else r["calls"], 2)]
        nm = {"S_1": "S$_1$", "RSI dynamic": "Dynamic R3 (+GRPO)"}.get(pol, pol)
        lab = NAME[b] if i == 0 else ""
        T.append(f"{lab} & {nm} & " + " & ".join(cells) + r" \\"); M.append(f"| {lab} | {md(nm)} | " + " | ".join(md(c) for c in cells) + " |")
    T.append(r"\midrule")
T[-1] = r"\bottomrule"; T += [r"\end{tabular}", r"\vspace{6pt}", "", r"\begin{tabular}{lrrr}", r"\toprule",
                                 r"Advisor tokens per call & Extractor & Reasoner & Verifier \\", r"\midrule"]
M += ["", "**Advisor tokens per call (input + output)**", "", "| Benchmark | Extractor | Reasoner | Verifier |", "|:--|--:|--:|--:|"]
for b in B:
    pc = TK[b]["advisor_tokens_per_call"]
    cells = [fmt(pc[k]) for k in ("extractor", "reasoner", "verifier")]
    T.append(f"{NAME[b]} & " + " & ".join(cells) + r" \\"); M.append(f"| {NAME[b]} | " + " | ".join(cells) + " |")
missing = [NAME[b] for b in B if TK[b]["rows"].get("RSI dynamic", {}).get("mgr_in") is None]
cap = ("Mean tokens per question on the locked tests by who reads or writes them" + (f" (Dynamic R3: only totals kept on {' and '.join(missing)}; S$_1$ there from its SFT-run evaluation)" if missing else "")
       + ". Per-call advisor tokens come from the base system, which makes 1.6--3.0 calls per question.")
write("tab_app_tokens", T + end(cap, "tab:app_tokens"), M, cap)

# ------------------------------------------------------------------ advisor mix
MX = A["mix"]
POL = ["S_1", "Dynamic R3", "Dynamic R5", "Static R3", "Static R5", "Dynamic R3 + GRPO", "Static R3 + GRPO", "Success R3 + GRPO"]
SHOWN = {"Dynamic R3": "Dynamic R3 (SFT)", "Dynamic R5": "Dynamic R5 (SFT)", "Static R3": "Static R3 (SFT)", "Static R5": "Static R5 (SFT)",
         "Dynamic R3 + GRPO": "Dynamic R3 (+GRPO)", "Static R3 + GRPO": "Static R3 (+GRPO)", "Success R3 + GRPO": "Success R3 (+GRPO)"}
T = begin("l" + "@{\\hspace{10pt}}".join(["rrr"] * len(B)), size="\\footnotesize", sep="4pt") + [r" & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{NAME[b]}}}" for b in B) + r" \\",
       " ".join(f"\\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(len(B))), "Policy" + " & E & R & V" * len(B) + r" \\", r"\midrule"]
M = ["| Policy | " + " | ".join(f"{NAME[b]} {c}" for b in B for c in "ERV") + " |", "|:--|" + "--:|" * (3 * len(B))]
for pol in POL:
    cells = []
    for b in B:
        r = MX[b].get(pol)
        cells += ["--"] * 3 if r is None else [q(r["per100"][k], 1) for k in ("extractor", "reasoner", "verifier")]
    nm = "S$_1$" if pol == "S_1" else SHOWN[pol]
    T.append(f"{nm} & " + " & ".join(cells) + r" \\"); M.append(f"| {md(nm)} | " + " | ".join(md(c) for c in cells) + " |")
    if pol in ("S_1", "Static R5"): T.append(r"\midrule")
cap = "Advisor calls per 100 locked-test questions by role (E = Extractor, R = Reasoner, V = Verifier)."
write("tab_app_mix", T + end(cap, "tab:app_mix"), M, cap)

# ------------------------------------------------------------------ MMLU-Pro test_paper
Lp = d["locked"]["mmlu_pro:test_paper"]; Pp = d["pairs"]["mmlu_pro:test_paper"]
T = begin("lrrr", star=False, sep="4pt") + [r"Policy & Acc. & Calls & $\Delta$ (p) \\", r"\midrule"]
M = ["| Policy | Acc. | Calls | Δ (p) |", "|:--|--:|--:|--:|"]
for nm, k in [("S$_1$", "v3g/S_1"), ("Static", "v3g/static"), ("Dynamic", "v3g/dynamic"), ("Success", "v3g/success")]:
    m = Lp[k]; a = exact(m["acc"], m["n"]); c = exact(m["calls"], m["n"], 1)
    if k == "v3g/S_1": dlt = "--"
    else:
        pr = Pp[f"{k} - v3g/S_1"]; dlt = f"{sgn(a - exact(Lp['v3g/S_1']['acc'], m['n']))} ({pv(pr['p'])})"
    cells = [q(a, 1), q(c, 2), dlt]
    T.append(f"{nm} & " + " & ".join(cells) + r" \\"); M.append(f"| {md(nm)} | " + " | ".join(md(x) for x in cells) + " |")
cap = f"The original paper's MMLU-Pro test pool ({Lp['v3g/S_1']['n']} questions, overlapping our training pools); round 3, SFT + GRPO; $\\Delta$ vs.\\ S$_1$ with paired-bootstrap p."
write("tab_app_testpaper", T + end(cap, "tab:app_testpaper", star=False), M, cap)
